function qOf(key?: string): I18nText | undefined {
  if (!key) return undefined;
  return Q[key];
}

export function compileChart(stage: StageDef): ChartNote[] {
  const beat = 60 / stage.bpm;
  return stage.notes.map((n: RawNote, i) => ({
    id: i,
    beat: n.b,
    time: n.b * beat,
    type: n.t,
    durationBeats: n.d ?? 0,
    duration: (n.d ?? 0) * beat,
    question: qOf(n.q),
    journalist: n.j,
    hint: n.hint,
  }));
}

export function stageDuration(stage: StageDef): number {
  return (stage.durationBeats + 8) * (60 / stage.bpm);
}

function mulberry32(a: number) {
  return function () {
    let t = (a += 0x6d2b79f5);
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

